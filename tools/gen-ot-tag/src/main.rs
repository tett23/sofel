//! Write sofel-shape's OpenType language tag table (ADR 0020). Run from
//! the repository root after `scripts/fetch-testdata.sh`:
//!
//!   cargo run --release --manifest-path tools/gen-ot-tag/Cargo.toml [-- ROOT]
//!
//! ROOT defaults to the current directory. Reads
//! `target/testdata/harfbuzz/src/hb-ot-tag-table.hh` and writes
//! `crates/sofel-shape/src/tag_table.rs`.

use std::fs;
use std::path::{Path, PathBuf};
use std::process::ExitCode;

use gen_ot_tag::{emit, lock_commit, parse};

const COMMAND: &str = "cargo run --release --manifest-path tools/gen-ot-tag/Cargo.toml";

fn read(path: &Path) -> Result<String, String> {
    fs::read_to_string(path).map_err(|e| format!("{}: {e}", path.display()))
}

fn run() -> Result<(), String> {
    let root = std::env::args()
        .nth(1)
        .map_or(PathBuf::from("."), PathBuf::from);
    let commit = lock_commit(&read(&root.join("testdata.lock"))?, "harfbuzz")?;
    let src = root.join("target/testdata/harfbuzz/src/hb-ot-tag-table.hh");
    let table = parse(&read(&src)?).map_err(|e| format!("{}: {e}", src.display()))?;
    let header = [
        format!("Generated by `{COMMAND}` (ADR 0020). Do not edit."),
        String::new(),
        "The arrays and the two generated functions of src/hb-ot-tag-table.hh".to_string(),
        format!("of HarfBuzz at commit {commit}"),
        "(testdata.lock), under the MIT license (THIRD_PARTY_NOTICES.md).".to_string(),
    ];
    let out = root.join("crates/sofel-shape/src/tag_table.rs");
    fs::write(&out, emit(&table, &header)).map_err(|e| format!("{}: {e}", out.display()))?;
    println!("wrote {}", out.display());
    Ok(())
}

fn main() -> ExitCode {
    match run() {
        Ok(()) => ExitCode::SUCCESS,
        Err(e) => {
            eprintln!("gen-ot-tag: {e}");
            ExitCode::FAILURE
        }
    }
}
