fn arabic_file(i: &ShaperInputs, aliases: &BTreeMap<String, String>) -> Result<String, String> {
    let shaping_text = i.ucd("ArabicShaping.txt")?;
    let joining = arabic::joining_types(&shaping_text)?;
    let scripts = arabic::joining_scripts(&shaping_text, &i.ucd("Scripts.txt")?, aliases)?;
    let s = arabic::shaping(&i.ucd("UnicodeData.txt")?)?;
    let table = packed_table(
        "joining_table",
        "The value of [`joining_type`].",
        &joining,
        arabic::JOINING_DEFAULT,
    )?;
    let mut header = i.header(
        "gen-arabic-table.py and src/gen-arabic-joining-list.py",
        &[
            "ArabicShaping.txt",
            "UnicodeData.txt",
            "Scripts.txt",
            "PropertyValueAliases.txt",
        ],
        &[],
    );
    header.push(format!(
        "SHAPING_TABLE: {} rows; LIGATURE_TABLE: {}, LIGATURE_MARK_TABLE: {},",
        s.table.len(),
        s.ligatures.len(),
        s.mark_ligatures.len()
    ));
    header.push(format!(
        "LIGATURE_3_TABLE: {} first components.",
        s.ligatures_3.len()
    ));

    let mut x = String::new();
    writeln!(
        x,
        "/// HarfBuzz's `joining_type` (`hb-ot-shaper-arabic-table.hh`): the\n\
         /// `hb_arabic_joining_type_t` of a character (0 U, 1 L, 2 R, 3 D or C,\n\
         /// 4 the Alaph group, 5 the Dalath-Rish group, 6 T, 7 X when not listed).\n\
         #[inline]\n\
         pub(crate) fn joining_type(cp: u32) -> u8 {{\n    \
         u8::try_from(joining_table(cp)).unwrap_or({})\n}}\n",
        arabic::JOINING_DEFAULT
    )
    .unwrap();
    let cells = |v: &[u32]| -> Result<String, String> {
        Ok(v.iter()
            .map(|&c| u16_of(c).map(|c| format!("{c:#06X}")))
            .collect::<Result<Vec<_>, _>>()?
            .join(", ")
            .replace("0X", "0x"))
    };
    writeln!(
        x,
        "/// The first character of [`SHAPING_TABLE`].\n\
         pub(crate) const SHAPING_TABLE_FIRST: u32 = {:#06X};\n\
         /// The last character of [`SHAPING_TABLE`].\n\
         pub(crate) const SHAPING_TABLE_LAST: u32 = {:#06X};\n",
        s.first,
        s.first + s.table.len() as u32 - 1
    )
    .unwrap();
    writeln!(
        x,
        "/// HarfBuzz's `shaping_table`: the initial, medial, final and isolated\n\
         /// presentation forms of each character from [`SHAPING_TABLE_FIRST`],\n\
         /// 0 for none.\n\
         pub(crate) const SHAPING_TABLE: [[u16; 4]; {}] = [",
        s.table.len()
    )
    .unwrap();
    for (k, row) in s.table.iter().enumerate() {
        writeln!(x, "    [{}], // U+{:04X}", cells(row)?, s.first + k as u32).unwrap();
    }
    writeln!(x, "];\n").unwrap();
    let two = |x: &mut String,
               name: &str,
               c_name: &str,
               t: &[(u32, Vec<(u32, u32)>)]|
     -> Result<(), String> {
        writeln!(
            x,
            "/// HarfBuzz's `{c_name}`: each first component with its\n\
             /// `([second component], ligature)` pairs, in HarfBuzz's order (without\n\
             /// HarfBuzz's padding of zeros).\n\
             #[allow(clippy::type_complexity)]\n\
             pub(crate) const {name}: [(u16, &[([u16; 1], u16)]); {}] = [",
            t.len()
        )
        .unwrap();
        for (first, ligas) in t {
            let pairs = ligas
                .iter()
                .map(|&(b, c)| Ok(format!("([{}], {})", cells(&[b])?, cells(&[c])?)))
                .collect::<Result<Vec<_>, String>>()?;
            writeln!(x, "    ({}, &[{}]),", cells(&[*first])?, pairs.join(", ")).unwrap();
        }
        writeln!(x, "];\n").unwrap();
        Ok(())
    };
    two(&mut x, "LIGATURE_TABLE", "ligature_table", &s.ligatures)?;
    two(
        &mut x,
        "LIGATURE_MARK_TABLE",
        "ligature_mark_table",
        &s.mark_ligatures,
    )?;
    writeln!(
        x,
        "/// HarfBuzz's `ligature_3_table`: each first component with its\n\
         /// `([second, third component], ligature)` triples, in HarfBuzz's order\n\
         /// (without HarfBuzz's padding of zeros).\n\
         #[allow(clippy::type_complexity)]\n\
         pub(crate) const LIGATURE_3_TABLE: [(u16, &[([u16; 2], u16)]); {}] = [",
        s.ligatures_3.len()
    )
    .unwrap();
    for (first, ligas) in &s.ligatures_3 {
        let triples = ligas
            .iter()
            .map(|&(b, c, l)| Ok(format!("([{}], {})", cells(&[b, c])?, cells(&[l])?)))
            .collect::<Result<Vec<_>, String>>()?;
        writeln!(x, "    ({}, &[{}]),", cells(&[*first])?, triples.join(", ")).unwrap();
    }
    writeln!(x, "];\n").unwrap();
    let tags: Vec<String> = scripts.iter().map(|t| format!("b\"{t}\"")).collect();
    writeln!(
        x,
        "/// HarfBuzz's `has_arabic_joining` (`hb-ot-shaper-arabic-joining-list.hh`):\n\
         /// whether a script (ISO 15924 tag) has characters that join.\n\
         pub(crate) fn has_arabic_joining(script: [u8; 4]) -> bool {{\n    \
         matches!(\n        &script,\n        {}\n    )\n}}",
        tags.join("\n            | ")
    )
    .unwrap();
    Ok(file(&header, &[table], &x))
}

fn vowel_file(i: &ShaperInputs, aliases: &BTreeMap<String, String>) -> Result<String, String> {
    let groups = vowel::by_script(
        &i.hb("ms-use/IndicShapingInvalidCluster.txt")?,
        &i.ucd("Scripts.txt")?,
    )?;
    let mut header = i.header(
        "gen-vowel-constraints.py",
        &["Scripts.txt", "PropertyValueAliases.txt"],
        &["ms-use/IndicShapingInvalidCluster.txt"],
    );
    header.push(String::new());
    header.push("The data is generated; the lookup after it is the generator's".to_string());
    header.push("hand-written text (tools/gen-unicode/src/vowel.rs).".to_string());
    let mut x = String::new();
    writeln!(
        x,
        "/// The sequences of each script (ISO 15924 tag), sorted; the third\n\
         /// character is 0 in a sequence of two. Scripts in the order of\n\
         /// `Scripts.txt`, as HarfBuzz's `switch`.\n\
         #[allow(clippy::type_complexity)]\n\
         pub(crate) const VOWEL_CONSTRAINTS: [([u8; 4], &[[u32; 3]]); {}] = [",
        groups.len()
    )
    .unwrap();
    for (script, seqs) in &groups {
        let tag = aliases
            .get(script)
            .ok_or(format!("unknown script {script}"))?;
        writeln!(x, "    (\n        *b\"{tag}\",\n        &[").unwrap();
        for s in seqs {
            let c: Vec<String> = s
                .iter()
                .chain(std::iter::repeat(&0))
                .take(3)
                .map(|c| format!("{c:#06X}").replace("0X", "0x"))
                .collect();
            writeln!(x, "            [{}],", c.join(", ")).unwrap();
        }
        writeln!(x, "        ],\n    ),").unwrap();
    }
    writeln!(x, "];\n").unwrap();
    x.push_str(vowel::LOOKUP);
    Ok(header_only(&header, &x))
}

/// The tables of `crates/sofel-shape/src/tables/`, by file name.
fn shaper_tables(root: &Path) -> Result<Vec<(&'static str, String)>, String> {
    let ucd = parse_lock(&read(&root.join("ucd.lock"))?)?;
    let version = unicode_version(
        &ucd.iter()
            .find(|l| l.path == "UnicodeData.txt")
            .ok_or("UnicodeData.txt is not in ucd.lock")?
            .url,
    )?;
    let harfbuzz = parse_lock(&read(&root.join("testdata.lock"))?)?
        .into_iter()
        .find(|l| l.path == "harfbuzz")
        .ok_or("harfbuzz is not in testdata.lock")?
        .sha256;
    let i = ShaperInputs {
        version,
        ucd,
        harfbuzz,
        root: root.to_path_buf(),
    };
    let aliases = ucd::parse_script_aliases(&i.ucd("PropertyValueAliases.txt")?);
    Ok(vec![
        ("indic.rs", indic_file(&i)?),
        ("use_.rs", use_file(&i)?),
        ("arabic.rs", arabic_file(&i, &aliases)?),
        ("vowel_constraints.rs", vowel_file(&i, &aliases)?),
    ])
}

fn run() -> Result<(), String> {
    let root = std::env::args()
        .nth(1)
        .map_or(PathBuf::from("."), PathBuf::from);
    let unicode = unicode_tables(&root)?;
    let pua = pua_tables(&root)?;
    let shaper = shaper_tables(&root)?;
    write(&root.join("crates/sofel-unicode/src/tables.rs"), &unicode)?;
    write(
        &root.join("crates/sofel-font/src/tables/arabic_pua.rs"),
        &pua,
    )?;
    let dir = root.join("crates/sofel-shape/src/tables");
    for (name, text) in &shaper {
        write(&dir.join(name), text)?;
    }
    Ok(())
}

fn main() -> ExitCode {
    match run() {
        Ok(()) => ExitCode::SUCCESS,
        Err(e) => {
            eprintln!("gen-unicode: {e}");
            ExitCode::FAILURE
        }
    }
}
