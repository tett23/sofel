//! Write sofel's generated Unicode tables (ADR 0019). Run from the
//! repository root after `scripts/fetch-ucd.sh` and
//! `scripts/fetch-testdata.sh`:
//!
//!   cargo run --release --manifest-path tools/gen-unicode/Cargo.toml [-- ROOT]
//!
//! ROOT defaults to the current directory. Writes
//! `crates/sofel-unicode/src/tables.rs`,
//! `crates/sofel-font/src/tables/arabic_pua.rs` and the shaper tables
//! `crates/sofel-shape/src/tables/{indic,use_,arabic,vowel_constraints}.rs`.

use std::collections::BTreeMap;
use std::fmt::Write;
use std::fs;
use std::path::{Path, PathBuf};
use std::process::ExitCode;

use gen_unicode::{
    LockLine, arabic, file, indic, packed_table, parse_lock, props, pua, ucd, unicode_version,
    use_table, vowel,
};

const COMMAND: &str = "cargo run --release --manifest-path tools/gen-unicode/Cargo.toml";

const UCD_FILES: [&str; 7] = [
    "UnicodeData.txt",
    "Scripts.txt",
    "PropertyValueAliases.txt",
    "BidiMirroring.txt",
    "DerivedNormalizationProps.txt",
    "emoji/emoji-data.txt",
    "VerticalOrientation.txt",
];

fn read(path: &Path) -> Result<String, String> {
    fs::read_to_string(path).map_err(|e| format!("{}: {e}", path.display()))
}

fn write(path: &Path, text: &str) -> Result<(), String> {
    if let Some(dir) = path.parent() {
        fs::create_dir_all(dir).map_err(|e| format!("{}: {e}", dir.display()))?;
    }
    fs::write(path, text).map_err(|e| format!("{}: {e}", path.display()))?;
    println!("wrote {}", path.display());
    Ok(())
}

fn unicode_tables(root: &Path) -> Result<String, String> {
    let lock = parse_lock(&read(&root.join("ucd.lock"))?)?;
    let entry = |name: &str| {
        lock.iter()
            .find(|l| l.path == name)
            .ok_or(format!("{name} is not in ucd.lock"))
    };
    let version = unicode_version(&entry("UnicodeData.txt")?.url)?;
    let ucd = root.join("target/ucd");
    let texts: Vec<String> = UCD_FILES
        .iter()
        .map(|f| read(&ucd.join(f)))
        .collect::<Result<_, _>>()?;
    let p = props::read(&props::Inputs {
        unicode_data: &texts[0],
        scripts: &texts[1],
        property_value_aliases: &texts[2],
        bidi_mirroring: &texts[3],
        derived_normalization_props: &texts[4],
        emoji_data: &texts[5],
        vertical_orientation: &texts[6],
    })?;

    let tables = [
        packed_table(
            "gc",
            "General_Category, as its position in HarfBuzz's\n`hb_unicode_general_category_t`.",
            &p.gc.values,
            p.gc.default,
        )?,
        packed_table(
            "ccc",
            "Canonical_Combining_Class.",
            &p.ccc.values,
            p.ccc.default,
        )?,
        packed_table(
            "sc",
            "Script, as an index of [`SCRIPT_TAGS`].",
            &p.sc.values,
            p.sc.default,
        )?,
        packed_table(
            "bmg",
            "Bidi_Mirroring_Glyph minus the code point, as an index of\n[`BMG_PALETTE`].",
            &p.bmg.values,
            p.bmg.default,
        )?,
        packed_table(
            "dm",
            "The canonical decomposition: 0 for none, `1..=DM1.len()` for\n`DM1[n - 1]`, then `DM2[n - 1 - DM1.len()]`.",
            &p.dm.values,
            p.dm.default,
        )?,
        packed_table(
            "ext_pict",
            "Extended_Pictographic, 0 or 1.",
            &p.ext_pict.values,
            p.ext_pict.default,
        )?,
        packed_table(
            "vo",
            "Vertical_Orientation: 0 U, 1 R, 2 Tu, 3 Tr.",
            &p.vo.values,
            p.vo.default,
        )?,
    ];

    let mut header = vec![
        format!("Generated by `{COMMAND}` (ADR 0019). Do not edit."),
        String::new(),
        format!(
            "Unicode {}.{}.{}, from the Unicode Character Database under the Unicode",
            version.0, version.1, version.2
        ),
        "License v3 (THIRD_PARTY_NOTICES.md). Inputs (SHA-256):".to_string(),
    ];
    for f in UCD_FILES {
        header.push(format!("  {f} {}", entry(f)?.sha256));
    }

    let mut extra = String::new();
    writeln!(extra, "/// The Unicode version of the tables.").unwrap();
    writeln!(
        extra,
        "pub(crate) const VERSION: (u8, u8, u8) = ({}, {}, {});",
        version.0, version.1, version.2
    )
    .unwrap();
    writeln!(extra).unwrap();
    writeln!(
        extra,
        "/// Bidi_Mirroring_Glyph minus the code point: 0, then the others sorted."
    )
    .unwrap();
    writeln!(
        extra,
        "pub(crate) const BMG_PALETTE: [i32; {}] = [",
        p.bmg_palette.len()
    )
    .unwrap();
    p.bmg_palette.chunks(8).for_each(|c| {
        let cells: Vec<String> = c.iter().map(|v| format!("{v},")).collect();
        writeln!(extra, "    {}", cells.join(" ")).unwrap();
    });
    writeln!(extra, "];").unwrap();
    writeln!(extra).unwrap();
    writeln!(extra, "/// ISO 15924 tags of the scripts, sorted.").unwrap();
    writeln!(
        extra,
        "pub(crate) const SCRIPT_TAGS: [[u8; 4]; {}] = [",
        p.script_tags.len()
    )
    .unwrap();
    p.script_tags.chunks(6).for_each(|c| {
        let cells: Vec<String> = c.iter().map(|t| format!("*b\"{t}\",")).collect();
        writeln!(extra, "    {}", cells.join(" ")).unwrap();
    });
    writeln!(extra, "];").unwrap();
    writeln!(extra).unwrap();
    writeln!(extra, "/// One-character canonical decompositions, sorted.").unwrap();
    writeln!(extra, "pub(crate) const DM1: [u32; {}] = [", p.dm1.len()).unwrap();
    p.dm1.chunks(8).for_each(|c| {
        let cells: Vec<String> = c.iter().map(|v| format!("{v:#07x},")).collect();
        writeln!(extra, "    {}", cells.join(" ")).unwrap();
    });
    writeln!(extra, "];").unwrap();
    writeln!(extra).unwrap();
    writeln!(
        extra,
        "/// Two-character canonical decompositions `(a << 42) | (b << 21) | ab`,\n/// sorted; `ab` is 0 if the pair does not compose."
    )
    .unwrap();
    writeln!(extra, "pub(crate) const DM2: [u64; {}] = [", p.dm2.len()).unwrap();
    p.dm2.chunks(4).for_each(|c| {
        let cells: Vec<String> = c.iter().map(|v| format!("{v:#018x},")).collect();
        writeln!(extra, "    {}", cells.join(" ")).unwrap();
    });
    writeln!(extra, "];").unwrap();

    Ok(file(&header, &tables, &extra))
}

fn pua_tables(root: &Path) -> Result<String, String> {
    let harfbuzz = parse_lock(&read(&root.join("testdata.lock"))?)?
        .into_iter()
        .find(|l| l.path == "harfbuzz")
        .ok_or("harfbuzz is not in testdata.lock")?;
    let src = root.join("target/testdata/harfbuzz/src");
    let simp = pua::parse(&read(&src.join("ArabicPUASimplified.txt"))?)?;
    let trad = pua::parse(&read(&src.join("ArabicPUATraditional.txt"))?)?;
    let tables = [
        packed_table(
            "simp_map",
            "The code of a character in the simplified Arabic symbol fonts, 0 if none\n(HarfBuzz's `_hb_arabic_pua_simp_map`).",
            &simp,
            0,
        )?,
        packed_table(
            "trad_map",
            "The code of a character in the traditional Arabic symbol fonts, 0 if\nnone (HarfBuzz's `_hb_arabic_pua_trad_map`).",
            &trad,
            0,
        )?,
    ];
    let header = vec![
        format!("Generated by `{COMMAND}` (ADR 0019). Do not edit."),
        String::new(),
        "The rules of HarfBuzz's src/gen-arabic-pua.py (MIT), applied to".to_string(),
        "src/ArabicPUASimplified.txt and src/ArabicPUATraditional.txt of HarfBuzz".to_string(),
        format!("at commit {} (testdata.lock).", harfbuzz.sha256),
    ];
    Ok(file(&header, &tables, ""))
}

/// The inputs of the shaper tables: their texts and the header lines
/// naming them.
struct ShaperInputs {
    version: (u8, u8, u8),
    ucd: Vec<LockLine>,
    harfbuzz: String,
    root: PathBuf,
}

impl ShaperInputs {
    fn ucd(&self, name: &str) -> Result<String, String> {
        read(&self.root.join("target/ucd").join(name))
    }

    fn hb(&self, name: &str) -> Result<String, String> {
        read(&self.root.join("target/testdata/harfbuzz/src").join(name))
    }

    /// The header of a generated shaper table.
    fn header(&self, script: &str, ucd_files: &[&str], hb_files: &[&str]) -> Vec<String> {
        let (a, b, c) = self.version;
        let mut h = vec![
            format!("Generated by `{COMMAND}` (ADR 0019). Do not edit."),
            String::new(),
            format!("The rules of HarfBuzz's src/{script} (MIT), applied to the Unicode"),
            format!("Character Database {a}.{b}.{c} under the Unicode License v3"),
            "(THIRD_PARTY_NOTICES.md). Inputs (SHA-256):".to_string(),
        ];
        for f in ucd_files {
            let sha = self
                .ucd
                .iter()
                .find(|l| l.path == *f)
                .map_or("(not in ucd.lock)", |l| l.sha256.as_str());
            h.push(format!("  {f} {sha}"));
        }
        h.push(format!(
            "HarfBuzz at commit {} (testdata.lock).",
            self.harfbuzz
        ));
        if !hb_files.is_empty() {
            h.push("HarfBuzz's inputs:".to_string());
        }
        for f in hb_files {
            h.push(format!("  src/{f}"));
        }
        if hb_files.iter().any(|f| f.starts_with("ms-use/")) {
            h.push(
                "The ms-use files are Microsoft's, under the MIT license (THIRD_PARTY_NOTICES.md)."
                    .to_string(),
            );
        }
        h
    }
}

fn header_only(header: &[String], body: &str) -> String {
    let mut out = String::new();
    header.iter().for_each(|l| {
        let sep = if l.is_empty() { "" } else { " " };
        writeln!(out, "//{sep}{l}").unwrap();
    });
    writeln!(out).unwrap();
    out.push_str(body);
    out
}

fn u16_of(v: u32) -> Result<u16, String> {
    u16::try_from(v).map_err(|_| format!("{v:#X} does not fit in 16 bits"))
}

fn indic_file(i: &ShaperInputs) -> Result<String, String> {
    let machines = [
        i.hb("hb-ot-shaper-indic-machine.rl")?,
        i.hb("hb-ot-shaper-khmer-machine.rl")?,
        i.hb("hb-ot-shaper-myanmar-machine.rl")?,
    ];
    let inputs = indic::Inputs {
        syllabic: &i.ucd("IndicSyllabicCategory.txt")?,
        positional: &i.ucd("IndicPositionalCategory.txt")?,
        blocks: &i.ucd("Blocks.txt")?,
        machines: [&machines[0], &machines[1], &machines[2]],
        indic_hh: &i.hb("hb-ot-shaper-indic.hh")?,
    };
    let (values, default) = indic::values(&inputs)?;
    let table = packed_table(
        "indic_table",
        "The value of [`indic_categories`].",
        &values,
        default,
    )?;
    let header = i.header(
        "gen-indic-table.py",
        &[
            "IndicSyllabicCategory.txt",
            "IndicPositionalCategory.txt",
            "Blocks.txt",
        ],
        &[
            "hb-ot-shaper-indic-machine.rl",
            "hb-ot-shaper-khmer-machine.rl",
            "hb-ot-shaper-myanmar-machine.rl",
            "hb-ot-shaper-indic.hh",
        ],
    );
    let extra = format!(
        "/// HarfBuzz's `hb_indic_get_categories`: the category of the indic,\n\
         /// khmer and myanmar shapers in the low byte (the numbers of their\n\
         /// machines' exports), the position (`ot_position_t`) in the high byte.\n\
         #[inline]\n\
         pub(crate) fn indic_categories(cp: u32) -> u16 {{\n    \
         u16::try_from(indic_table(cp)).unwrap_or({default:#06x})\n}}\n"
    );
    Ok(file(&header, &[table], &extra))
}

