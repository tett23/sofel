//! Write sofel-shape's syllable state machines (ADR 0024). Run from the
//! repository root after `scripts/fetch-testdata.sh`:
//!
//!   cargo run --release --manifest-path tools/gen-machine/Cargo.toml [-- ROOT]
//!
//! ROOT defaults to the current directory. Reads
//! `tools/gen-machine/grammars/<name>.machine` and writes
//! `crates/sofel-shape/src/tables/machine_<name>.rs` for each machine.

use std::fs;
use std::path::{Path, PathBuf};
use std::process::ExitCode;

const COMMAND: &str = "cargo run --release --manifest-path tools/gen-machine/Cargo.toml";

/// The machines: name, HarfBuzz's grammar file.
const MACHINES: [(&str, &str); 4] = [
    ("indic", "src/hb-ot-shaper-indic-machine.rl"),
    ("khmer", "src/hb-ot-shaper-khmer-machine.rl"),
    ("myanmar", "src/hb-ot-shaper-myanmar-machine.rl"),
    ("use", "src/hb-ot-shaper-use-machine.rl"),
];

/// Inputs up to this length are checked against the automaton before
/// determinization.
const VERIFY_LEN: usize = 3;

fn read(path: &Path) -> Result<String, String> {
    fs::read_to_string(path).map_err(|e| format!("{}: {e}", path.display()))
}

fn harfbuzz_commit(root: &Path) -> Result<String, String> {
    read(&root.join("testdata.lock"))?
        .lines()
        .map(str::split_whitespace)
        .find_map(|mut w| (w.next() == Some("harfbuzz")).then(|| w.nth(1)).flatten())
        .map(str::to_string)
        .ok_or_else(|| "harfbuzz is not in testdata.lock".to_string())
}

fn run() -> Result<(), String> {
    let root = std::env::args()
        .nth(1)
        .map_or(PathBuf::from("."), PathBuf::from);
    let commit = harfbuzz_commit(&root)?;
    let out: Vec<(PathBuf, String)> = MACHINES
        .iter()
        .map(|(name, rl)| {
            let path = root.join(format!("tools/gen-machine/grammars/{name}.machine"));
            let g = gen_machine::parse(&read(&path)?).map_err(|e| format!("{name}: {e}"))?;
            let (cls, dfa) = gen_machine::compile(&g);
            gen_machine::verify(&g, &cls, &dfa, VERIFY_LEN).map_err(|e| format!("{name}: {e}"))?;
            let header = vec![
                format!("Generated by `{COMMAND}` (ADR 0024). Do not edit."),
                String::new(),
                format!("From tools/gen-machine/grammars/{name}.machine, the rules of HarfBuzz's"),
                format!("{rl} (MIT) at commit {commit}."),
            ];
            let src = gen_machine::emit(name, &header, &g, &cls, &dfa);
            Ok((
                root.join(format!("crates/sofel-shape/src/tables/machine_{name}.rs")),
                src,
            ))
        })
        .collect::<Result<_, String>>()?;
    for (path, src) in out {
        fs::write(&path, src).map_err(|e| format!("{}: {e}", path.display()))?;
        println!("wrote {}", path.display());
    }
    Ok(())
}

fn main() -> ExitCode {
    match run() {
        Ok(()) => ExitCode::SUCCESS,
        Err(e) => {
            eprintln!("gen-machine: {e}");
            ExitCode::FAILURE
        }
    }
}
