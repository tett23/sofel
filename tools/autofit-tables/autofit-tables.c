/*
 * autofit-tables: write the data tables of FreeType's automatic hinter as
 * Rust source for sofel-outline (sofel ADR 0064).
 *
 * The program includes FreeType's own `src/autofit/autofit.c`, so the
 * tables are those the C preprocessor builds from `afscript.h`,
 * `afstyles.h`, `afranges.c`, `afblue.c` and `afadjust.c` with the
 * configuration that tools/ft-dump uses (no HarfBuzz, CJK and Indic
 * writing systems enabled). Run tools/autofit-tables/build.sh; it writes
 * crates/sofel-outline/src/autofit/tables.rs.
 *
 * The tables are part of FreeType 2.15.0, copyright (C) 2003-2026 by
 * David Turner, Robert Wilhelm, and Werner Lemberg, used under the
 * FreeType License (FTL); see THIRD_PARTY_NOTICES.md.
 */

#include "autofit.c"

#include <stdio.h>

static void
print_bytes( const char*  s,
             size_t       n )
{
  size_t  i;


  putchar( 'b' );
  putchar( '"' );
  for ( i = 0; i < n; i++ )
  {
    unsigned char  c = (unsigned char)s[i];


    if ( c >= 0x20 && c < 0x7F && c != '"' && c != '\\' )
      putchar( c );
    else
      printf( "\\x%02X", c );
  }
  putchar( '"' );
}


static void
print_ranges( const AF_Script_UniRangeRec*  r )
{
  printf( "&[" );
  for ( ; r->first != 0; r++ )
    printf( "(0x%lX, 0x%lX), ", (unsigned long)r->first, (unsigned long)r->last );
  printf( "]" );
}


int
main( void )
{
  size_t  i;


  printf( "// Generated by tools/autofit-tables from FreeType 2.15.0\n"
          "// (src/autofit/afscript.h, afstyles.h, afranges.c, afblue.c,\n"
          "// afadjust.c). Copyright (C) 2003-2026 by David Turner, Robert\n"
          "// Wilhelm, and Werner Lemberg. Used under the FreeType License\n"
          "// (FTL); see THIRD_PARTY_NOTICES.md. Do not edit.\n\n" );
  printf( "#![allow(clippy::unreadable_literal)]\n\n" );
  printf( "use super::{BlueStringRec, ScriptClass, StyleClass, WritingSystem};\n\n" );

  printf( "/// `af_blue_strings`: UTF-8 strings, each ended by a zero byte.\n" );
  printf( "pub(super) const BLUE_STRINGS: &[u8] = " );
  print_bytes( af_blue_strings, sizeof ( af_blue_strings ) );
  printf( ";\n\n" );

  printf( "/// `AF_BLUE_STRING_MAX`, the end marker of a blue string set.\n" );
  printf( "pub(super) const BLUE_STRING_MAX: u16 = %u;\n\n",
          (unsigned)AF_BLUE_STRING_MAX );

  printf( "/// `af_blue_stringsets`.\n" );
  printf( "pub(super) const BLUE_STRINGSETS: &[BlueStringRec] = &[\n" );
  for ( i = 0; i < sizeof ( af_blue_stringsets ) / sizeof ( af_blue_stringsets[0] ); i++ )
    printf( "    BlueStringRec { string: %u, properties: %u },\n",
            (unsigned)af_blue_stringsets[i].string,
            (unsigned)af_blue_stringsets[i].properties );
  printf( "];\n\n" );

  printf( "/// `af_script_classes`.\n" );
  printf( "pub(super) const SCRIPTS: &[ScriptClass] = &[\n" );
  for ( i = 0; af_script_classes[i]; i++ )
  {
    AF_ScriptClass  sc = af_script_classes[i];


    printf( "    ScriptClass {\n        ranges: " );
    print_ranges( sc->script_uni_ranges );
    printf( ",\n        nonbase_ranges: " );
    print_ranges( sc->script_uni_nonbase_ranges );
    printf( ",\n        top_to_bottom: %s,\n        standard: ",
            sc->top_to_bottom_hinting ? "true" : "false" );
    print_bytes( sc->standard_charstring, strlen( sc->standard_charstring ) );
    printf( ",\n    },\n" );
  }
  printf( "];\n\n" );

  printf( "/// `af_style_classes`.\n" );
  printf( "pub(super) const STYLES: &[StyleClass] = &[\n" );
  for ( i = 0; af_style_classes[i]; i++ )
  {
    AF_StyleClass  st = af_style_classes[i];
    const char*    ws[] = { "Dummy", "Latin", "Cjk", "Indic" };


    printf( "    StyleClass { writing_system: WritingSystem::%s, script: %u,"
            " blue_stringset: %u, default_coverage: %s },\n",
            ws[st->writing_system],
            (unsigned)st->script,
            (unsigned)st->blue_stringset,
            st->coverage == AF_COVERAGE_DEFAULT ? "true" : "false" );
  }
  printf( "];\n\n" );

  printf( "/// `AF_STYLE_NONE_DFLT`.\n" );
  printf( "pub(super) const STYLE_NONE_DFLT: u16 = %u;\n", (unsigned)AF_STYLE_NONE_DFLT );
  printf( "/// `AF_STYLE_FALLBACK` (`AF_STYLE_HANI_DFLT`).\n" );
  printf( "pub(super) const STYLE_FALLBACK: u16 = %u;\n\n", (unsigned)AF_STYLE_FALLBACK );

  printf( "/// `adjustment_database` in table order (not fully sorted).\n" );
  printf( "pub(super) const ADJUSTMENTS: &[(u32, u32)] = &[\n" );
  for ( i = 0; i < AF_ADJUSTMENT_DATABASE_LENGTH; i++ )
    printf( "    (0x%lX, 0x%lX),\n",
            (unsigned long)adjustment_database[i].codepoint,
            (unsigned long)adjustment_database[i].flags );
  printf( "];\n" );

  return 0;
}
