use alloc::vec::Vec;

use crate::Scratch;

#[derive(Clone, Copy)]
struct Bounds {
    first: usize,
    last: usize,
    min_x: i32,
    max_x: i32,
    min_y: i32,
    max_y: i32,
}

fn bounds(scratch: &Scratch) -> Option<Vec<Bounds>> {
    let mut result = Vec::with_capacity(scratch.ends.len());
    let mut first = 0;
    for &last in &scratch.ends {
        let points = scratch.points.get(first..=last)?;
        let mut min_x = i32::MAX;
        let mut max_x = i32::MIN;
        let mut min_y = i32::MAX;
        let mut max_y = i32::MIN;
        for point in points {
            min_x = min_x.min(point.x);
            max_x = max_x.max(point.x);
            min_y = min_y.min(point.y);
            max_y = max_y.max(point.y);
        }
        result.push(Bounds {
            first,
            last,
            min_x,
            max_x,
            min_y,
            max_y,
        });
        first = last.checked_add(1)?;
    }
    (first == scratch.points.len()).then_some(result)
}

/// Apply the `AF_ADJUST_UP` path after the automatic hinter has aligned points.
/// Return false when the conservative accent-height boundary is exceeded.
pub(super) fn adjust_up(scratch: &mut Scratch, ppem: u16) -> bool {
    let Some(contours) = bounds(scratch) else {
        return false;
    };
    if contours.len() < 2 {
        return true;
    }
    let Some((high_index, high)) = contours
        .iter()
        .enumerate()
        .rev()
        .max_by_key(|(_, contour)| (contour.max_y, contour.min_y))
    else {
        return false;
    };
    let Some(height) = high.max_y.checked_sub(high.min_y) else {
        return false;
    };
    // FreeType derives the height limit from scaled blue zones. The supported
    // short-accent range is bounded to 1/8 em until those metrics are exposed.
    if height <= 64 || height > i32::from(ppem).saturating_mul(8) {
        return false;
    }
    let mut others_min_x = i32::MAX;
    let mut others_max_x = i32::MIN;
    for (index, contour) in contours.iter().enumerate() {
        if index != high_index && contour.last.saturating_sub(contour.first) >= 2 {
            others_min_x = others_min_x.min(contour.min_x);
            others_max_x = others_max_x.max(contour.max_x);
        }
    }
    let overlaps = others_min_x <= high.max_x && high.min_x <= others_max_x;
    if !overlaps {
        return true;
    }
    let mut distance = 64;
    for (index, contour) in contours.iter().enumerate() {
        if index == high_index {
            continue;
        }
        let candidate = high.min_y.saturating_sub(contour.max_y);
        if candidate < distance && contour.min_y < high.min_y {
            distance = candidate;
        }
    }
    let adjustment = 64i32.saturating_sub(distance);
    if adjustment == 0 || adjustment > 66 {
        return true;
    }
    let limit = high.min_y.saturating_sub(height / 8);
    for contour in contours {
        if contour.min_y < contour.max_y && contour.min_y > limit {
            let Some(points) = scratch.points.get_mut(contour.first..=contour.last) else {
                return false;
            };
            for point in points {
                point.y = point.y.saturating_add(adjustment);
            }
        }
    }
    true
}
