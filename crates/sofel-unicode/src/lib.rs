//! The Unicode character properties that shaping uses, from the Unicode
//! Character Database 18.0.0, the version of HarfBuzz 15.1.0's tables
//! (ADR 0019).
//!
//! The values and the defaults beyond each table are those of HarfBuzz's
//! default Unicode functions (`hb-ucd`): [`general_category`],
//! [`combining_class`], [`script`], [`mirroring`], [`decompose`] and
//! [`compose`], and [`is_extended_pictographic`]. [`vertical_orientation`]
//! (UAX #50), which HarfBuzz does not have, lets a caller split vertical
//! text into upright runs and runs set horizontally and rotated.
//!
//! Every function looks up constant tables generated by
//! `tools/gen-unicode/`; none allocates. The tables are derived from the
//! Unicode Character Database under the Unicode License v3. The Hangul
//! composition and decomposition follow HarfBuzz 15.1.0 (commit
//! 3df40d9b98d6b32f0e4288d4ecfbb158ddb3a372) `src/hb-ucd.cc`, and
//! [`Script::from_iso15924`] follows `src/hb-common.cc`
//! (`hb_script_from_iso15924_tag`); HarfBuzz is under the MIT license. See
//! THIRD_PARTY_NOTICES.md.

