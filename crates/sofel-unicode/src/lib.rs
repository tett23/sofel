/// A script tag. OpenType conversions can preserve HarfBuzz values outside
/// ISO 15924, including aliases and non-letter bytes.
#[derive(Clone, Copy, Debug, PartialEq, Eq, Hash, PartialOrd, Ord)]
pub struct Script([u8; 4]);

impl Script {
    /// Common (`Zyyy`).
    pub const COMMON: Script = Script(*b"Zyyy");
    /// Inherited (`Zinh`).
    pub const INHERITED: Script = Script(*b"Zinh");
    /// Unknown (`Zzzz`), the script of unassigned code points.
    pub const UNKNOWN: Script = Script(*b"Zzzz");

    /// The four bytes of the script value, including OpenType-derived values.
    pub const fn tag(self) -> [u8; 4] {
        self.0
    }

    /// Keeps a converted OpenType script value exactly as HarfBuzz returned it.
    pub const fn from_raw_tag(tag: [u8; 4]) -> Script {
        Script(tag)
    }

    /// The script of a four-letter ISO 15924 tag, like HarfBuzz's
    /// `hb_script_from_string`: the case is adjusted to one capital and
    /// three small letters, the variants HarfBuzz knows (`Aran`, `Latf`,
    /// `Hans`, ...) map to their script, and the Unicode aliases `Qaai`
    /// and `Qaac` map to Inherited and Coptic. A tag of letters that is
    /// not a script is still returned, as in HarfBuzz. `None` if `tag` is
    /// not four bytes or not letters.
    pub fn from_iso15924(tag: &[u8]) -> Option<Script> {
        let &[a, b, c, d] = tag else {
            return None;
        };
        let t = (u32::from_be_bytes([a, b, c, d]) & 0xDFDF_DFDF) | 0x0020_2020;
        let mapped = match &t.to_be_bytes() {
            b"Aran" => *b"Arab",
            b"Cyrs" => *b"Cyrl",
            b"Geok" => *b"Geor",
            b"Hans" | b"Hant" => *b"Hani",
            b"Jamo" => *b"Hang",
            b"Latf" | b"Latg" => *b"Latn",
            b"Syre" | b"Syrj" | b"Syrn" => *b"Syrc",
            b"Qaai" => *b"Zinh",
            b"Qaac" => *b"Copt",
            other => *other,
        };
        let letters = mapped.iter().enumerate().all(|(i, &x)| {
            let base = if i == 0 { b'A' } else { b'a' };
            (base..=base.saturating_add(25)).contains(&x)
        });
        letters.then_some(Script(mapped))
    }
}

/// Vertical_Orientation (UAX #50): how a character is set in vertical
/// text. A caller sets runs of `U` and `Tu` upright and runs of `R` and
/// `Tr` horizontally, rotated 90 degrees; `Tu` and `Tr` characters have
/// vertical alternates in fonts that support them.
#[derive(Clone, Copy, Debug, PartialEq, Eq, Hash)]
#[repr(u8)]
pub enum VerticalOrientation {
    /// Upright.
    U = 0,
    /// Rotated 90 degrees clockwise.
    R = 1,
    /// Transformed (a vertical alternate), else upright.
    Tu = 2,
    /// Transformed (a vertical alternate), else rotated.
    Tr = 3,
}

const VERTICAL_ORIENTATIONS: [VerticalOrientation; 4] = [
    VerticalOrientation::U,
    VerticalOrientation::R,
    VerticalOrientation::Tu,
    VerticalOrientation::Tr,
];

fn at<T: Copy>(table: &[T], i: u32) -> Option<T> {
    usize::try_from(i).ok().and_then(|i| table.get(i)).copied()
}

/// General_Category of `cp`; Unassigned beyond U+10FFFF.
pub fn general_category(cp: u32) -> GeneralCategory {
    at(&GENERAL_CATEGORIES, tables::gc(cp)).unwrap_or(GeneralCategory::Unassigned)
}

/// Canonical_Combining_Class of `cp`; 0 beyond U+10FFFF.
pub fn combining_class(cp: u32) -> u8 {
    u8::try_from(tables::ccc(cp)).unwrap_or(0)
}

/// Script of `cp`; Unknown beyond U+10FFFF.
pub fn script(cp: u32) -> Script {
    at(&tables::SCRIPT_TAGS, tables::sc(cp)).map_or(Script::UNKNOWN, Script)
}

/// Bidi_Mirroring_Glyph of `cp`; `cp` itself if it has none.
pub fn mirroring(cp: u32) -> u32 {
    cp.wrapping_add_signed(at(&tables::BMG_PALETTE, tables::bmg(cp)).unwrap_or(0))
}

/// Extended_Pictographic of `cp`.
pub fn is_extended_pictographic(cp: u32) -> bool {
    tables::ext_pict(cp) != 0
}

/// Vertical_Orientation of `cp`; `R` beyond U+10FFFF (the `@missing`
/// value of `VerticalOrientation.txt`).
pub fn vertical_orientation(cp: u32) -> VerticalOrientation {
    at(&VERTICAL_ORIENTATIONS, tables::vo(cp)).unwrap_or(VerticalOrientation::R)
}

const S_BASE: u32 = 0xAC00;
const L_BASE: u32 = 0x1100;
const V_BASE: u32 = 0x1161;
const T_BASE: u32 = 0x11A7;
const L_COUNT: u32 = 19;
const V_COUNT: u32 = 21;
const T_COUNT: u32 = 28;
const N_COUNT: u32 = V_COUNT * T_COUNT;
const S_COUNT: u32 = L_COUNT * N_COUNT;

fn decompose_hangul(ab: u32) -> Option<(u32, u32)> {
    let si = ab.checked_sub(S_BASE).filter(|&si| si < S_COUNT)?;
    let t = si % T_COUNT;
    if t != 0 {
        Some((ab.wrapping_sub(t), T_BASE.wrapping_add(t)))
    } else {
        Some((
            L_BASE.wrapping_add(si / N_COUNT),
            V_BASE.wrapping_add((si % N_COUNT) / T_COUNT),
        ))
    }
}

fn compose_hangul(a: u32, b: u32) -> Option<u32> {
    let lv_t = a
        .checked_sub(S_BASE)
        .filter(|&si| si < S_COUNT && si % T_COUNT == 0)
        .and(b.checked_sub(T_BASE))
        .filter(|&ti| ti > 0 && ti < T_COUNT)
        .map(|ti| a.wrapping_add(ti));
    let l_v = || {
        let li = a.checked_sub(L_BASE).filter(|&li| li < L_COUNT)?;
        let vi = b.checked_sub(V_BASE).filter(|&vi| vi < V_COUNT)?;
        Some(
            S_BASE
                .wrapping_add(li.wrapping_mul(N_COUNT))
                .wrapping_add(vi.wrapping_mul(T_COUNT)),
        )
    };
    lv_t.or_else(l_v)
}

const CODE: u64 = 0x1F_FFFF;

/// The canonical decomposition of `cp` by one step, like HarfBuzz's
/// `hb_unicode_decompose`: `(a, b)` for a decomposition into two
/// characters, `(a, 0)` for one into a single character, `None` if `cp`
/// does not decompose. Hangul syllables decompose by arithmetic, into
/// L and V or into LV and T.
pub fn decompose(cp: u32) -> Option<(u32, u32)> {
    decompose_hangul(cp).or_else(|| {
        let i = tables::dm(cp).checked_sub(1)?;
        at(&tables::DM1, i).map(|a| (a, 0)).or_else(|| {
            let len = u32::try_from(tables::DM1.len()).ok()?;
            let e = at(&tables::DM2, i.checked_sub(len)?)?;
            let a = u32::try_from(e >> 42).ok()?;
            let b = u32::try_from((e >> 21) & CODE).ok()?;
            Some((a, b))
        })
    })
}

/// The primary composite of `a` and `b`, like HarfBuzz's
/// `hb_unicode_compose`: `None` if either is 0, if the pair is not a
/// canonical decomposition, or if the composite is a full composition
/// exclusion or has a non-zero combining class. Hangul syllables compose
/// by arithmetic. Code points beyond U+10FFFF never compose.
pub fn compose(a: u32, b: u32) -> Option<u32> {
    if a == 0 || b == 0 {
        return None;
    }
    compose_hangul(a, b).or_else(|| {
        if a > 0x10_FFFF || b > 0x10_FFFF {
            return None;
        }
        let key = (u64::from(a) << 42) | (u64::from(b) << 21);
        let i = tables::DM2
            .binary_search_by(|e| (e & !CODE).cmp(&key))
            .ok()?;
        let ab = at(&tables::DM2, u32::try_from(i).ok()?)? & CODE;
        u32::try_from(ab).ok().filter(|&ab| ab != 0)
    })
}
